import { test, expect } from './helpers/state'
import { chooseMember, login } from './helpers/ui'

test('Timeline scheduling, cooked outbox delivery, journal serving count and member vote persist', async ({ page }) => {
  await login(page)
  await expect(page.locator('.timeline-day-column')).toHaveCount(9)
  const today = page.locator('.timeline-day-column.is-today')
  await expect(page.locator('.timeline-day-column.is-past')).toHaveCount(2)
  const date = await page.evaluate(() => new Date().toLocaleDateString('en-CA'))
  const before = await (await page.request.get(`/api/schedule?from=${date}&to=${date}`)).json()
  await today.locator('.add-btn').first().click()
  const dialog = page.locator('.modal-dialog')
  await dialog.locator('.search-box input').fill('Grandma')
  await dialog.locator('.recipe-results .select-btn').first().click()
  await expect(dialog).not.toBeVisible()
  const card = today.locator('.schedule-card').filter({ hasText: "Grandma's Tomato Pasta" })
  await expect(card).toBeVisible()
  const after = await (await page.request.get(`/api/schedule?from=${date}&to=${date}`)).json()
  const planned = after.find((row: any) => !before.some((previous: any) => previous.id === row.id))
  expect(planned.recipe_id).toBeTruthy()
  await card.click()
  await page.getByRole('menuitem', { name: 'Mark as cooked', exact: true }).click()
  await expect.poll(async () => (await (await page.request.get(`/api/journal?from=${date}&to=${date}`)).json()).filter((row: any) => row.schedule_entry_id === planned.id)).toHaveLength(1)
  await expect(card.getByTitle('Cooked')).toBeVisible()
  await page.reload()
  await expect(card.getByTitle('Cooked')).toBeVisible()
  const rows = await (await page.request.get(`/api/journal?from=${date}&to=${date}`)).json()
  const cooked = rows.find((row: any) => row.schedule_entry_id === planned.id)
  await page.getByRole('link', { name: 'Journal', exact: true }).first().click()
  await chooseMember(page, 'Alex')
  const member = (await (await page.request.get('/api/members')).json()).find((row: any) => row.name === 'Alex')
  const journalCard = page.locator('.journal-entry-card').filter({ hasText: "Grandma's Tomato Pasta" })
  await expect(journalCard).toContainText(`${cooked.servings_cooked} servings`)
  await journalCard.locator('.upvote-btn').click()
  await expect.poll(async () => (await (await page.request.get(`/api/x/core-ratings?journal_id=${cooked.id}`)).json()).scores).toEqual([{ member_id: member.id, score: 1 }])
  await page.reload()
  await expect(journalCard.locator('.upvote-btn')).toHaveAttribute('aria-pressed', 'true')
})
