import { test, expect } from './helpers/state'
import { chooseMember, login } from './helpers/ui'

test('Timeline scheduling, cooked outbox delivery, inline serving count and member vote persist', async ({ page }) => {
  await login(page)
  await expect(page.getByRole('link', { name: 'Journal', exact: true })).toHaveCount(0)
  await expect(page.locator('[data-timeline-date]')).toHaveCount(9)
  const today = page.locator('.day-card.is-today')
  await expect(page.locator('.past-day-line')).toHaveCount(2)
  const date = await page.evaluate(() => new Date().toLocaleDateString('en-CA'))
  const before = await (await page.request.get(`/api/timeline?from=${date}&to=${date}`)).json()
  await today.locator('[data-slot-id=dinner]').getByRole('button', { name: 'Add meal', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Search recipes', { exact: true }).fill('Grandma')
  await dialog.getByRole('button', { name: 'Schedule', exact: true }).first().click()
  await expect(dialog).not.toBeVisible()
  const card = today.locator('.schedule-card').filter({ hasText: "Grandma's Tomato Pasta" })
  await expect(card).toBeVisible()
  const after = await (await page.request.get(`/api/timeline?from=${date}&to=${date}`)).json()
  const planned = after.find((row: any) => !before.some((previous: any) => previous.id === row.id))
  expect(planned.recipe_id).toBeTruthy()
  expect(planned.status).toBe('planned')
  await card.locator('.schedule-card-main').click()
  await page.getByRole('menuitem', { name: 'Mark as cooked', exact: true }).click()
  await expect.poll(async () => {
    const rows = await (await page.request.get(`/api/timeline?from=${date}&to=${date}`)).json()
    return rows.find((row: any) => row.id === planned.id)?.status
  }).toBe('cooked')
  await expect(card.getByTitle('Cooked')).toBeVisible()
  await page.reload()
  await expect(card.getByTitle('Cooked')).toBeVisible()
  await expect(card).toContainText(`${planned.servings_override} servings`)
  await chooseMember(page, 'Alex')
  const member = (await (await page.request.get('/api/members')).json()).find((row: any) => row.name === 'Alex')
  await card.locator('.upvote-btn').click()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect.poll(async () => (await (await page.request.get(`/api/x/core-ratings?timeline_entry_id=${planned.id}`)).json()).scores).toEqual([{ member_id: member.id, score: 1 }])
  await page.reload()
  await expect(card.locator('.upvote-btn')).toHaveAttribute('aria-pressed', 'true')
})
